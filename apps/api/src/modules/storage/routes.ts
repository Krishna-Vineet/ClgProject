import { UPLOADABLE_FILE_PURPOSES, type UploadableFilePurpose } from "@campusops/shared";
import { Hono } from "hono";
import { z } from "zod";
import { authenticate } from "../../middleware/auth";
import { parseJson } from "../../middleware/validate";
import { ApiError } from "../../utils/api-error";
import { ok } from "../../utils/response";
import { auditContext, writeAudit } from "../audit/service";
import * as service from "./service";

const presignSchema = z.object({
  purpose: z.enum([
    "PROFILE_PHOTO",
    "COLLEGE_ID_PROOF",
    "EVENT_BANNER",
    "EVENT_REPORT",
    "ATTENDEE_EXPORT",
    "COMPLAINT_ATTACHMENT",
  ]),
  mimeType: z.string().min(3).max(100),
  sizeBytes: z.number().int().positive(),
});

export const storageRoutes = new Hono();
storageRoutes.use("*", authenticate);
storageRoutes.get("/config", (c) => ok(c, service.storagePublicConfig()));
storageRoutes.post("/presign", async (c) => {
  const input = await parseJson(c, presignSchema);
  // Account proofs and event banners are user-uploaded. Event reports are produced
  // server-side (see modules/reports), and attendee exports / complaint attachments
  // arrive with their own phases, so they are not accepted here.
  if (!UPLOADABLE_FILE_PURPOSES.includes(input.purpose as UploadableFilePurpose)) {
    throw new ApiError(
      "FORBIDDEN",
      input.purpose === "EVENT_REPORT"
        ? "Event reports are generated by the server. Use POST /events/:id/reports."
        : "This file purpose is not open for direct upload yet.",
    );
  }
  const result = await service.presignUpload(c.get("auth").user.id, input, auditContext(c));
  return ok(c, result, 201);
});
storageRoutes.post("/:id/complete", async (c) => {
  const result = await service.completeUpload(
    c.get("auth").user.id,
    c.req.param("id"),
    auditContext(c),
  );
  return ok(c, result);
});
storageRoutes.get("/:id/download", async (c) => {
  await service.getOwnedFile(c.get("auth").user.id, c.req.param("id"));
  const result = await service.signedDownload(c.req.param("id"));
  await writeAudit(c, {
    action: "FILE_DOWNLOADED",
    entityType: "file",
    entityId: c.req.param("id"),
  });
  return ok(c, result);
});
