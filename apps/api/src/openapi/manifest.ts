/** Convert a Hono route path to OpenAPI templating. */
export function toOpenApiPath(path: string): string {
  return path.replace(/:([A-Za-z0-9_]+)/g, "{$1}");
}

export function jsonSchema(schema: z.ZodTypeAny): Record<string, unknown> {
  const converted = zodToJsonSchema(schema, { target: "openApi3", $refStrategy: "none" }) as Record<
    string,
    unknown
  >;
  // zod-to-json-schema adds a $schema key that OpenAPI 3.1 does not want inline.
  const { $schema: _ignored, ...rest } = converted;
  return rest;
}
